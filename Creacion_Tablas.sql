-- SCHEMA: speedkitchen

-- DROP SCHEMA IF EXISTS speedkitchen ;

CREATE SCHEMA IF NOT EXISTS speedkitchen
    AUTHORIZATION postgres;

-- 1. ROLES
CREATE TABLE roles (
    id_rol INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(50) UNIQUE
);

-- 2. USUARIOS
CREATE TABLE usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INT,
    nombre VARCHAR(100),
    email VARCHAR(150) UNIQUE,
    password_hash VARCHAR(255),
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_usuarios_roles
        FOREIGN KEY (id_rol) REFERENCES roles(id_rol)
);

-- 3. AMIGOS
CREATE TABLE amigos (
    id_usuario_origen BIGINT,
    id_usuario_destino BIGINT,
    estado_solicitud VARCHAR(20),

    PRIMARY KEY (id_usuario_origen, id_usuario_destino),

    CONSTRAINT fk_amigos_usuario_origen
        FOREIGN KEY (id_usuario_origen) REFERENCES usuarios(id_usuario),

    CONSTRAINT fk_amigos_usuario_destino
        FOREIGN KEY (id_usuario_destino) REFERENCES usuarios(id_usuario)
);

-- 4. RECETAS
CREATE TABLE recetas (
    id_receta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_autor BIGINT,
    nombre VARCHAR(150),
    descripcion TEXT,
    modo_juego VARCHAR(50),

    CONSTRAINT fk_recetas_usuarios
        FOREIGN KEY (id_autor) REFERENCES usuarios(id_usuario)
);

-- 5. INGREDIENTES
CREATE TABLE ingredientes (
    id_ingrediente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) UNIQUE
);

-- 6. RECETAS_INGREDIENTES
CREATE TABLE recetas_ingredientes (
    id_receta BIGINT,
    id_ingrediente BIGINT,
    cantidad DECIMAL(10,2),
    unidad_medida VARCHAR(50),

    PRIMARY KEY (id_receta, id_ingrediente),

    CONSTRAINT fk_ri_recetas
        FOREIGN KEY (id_receta) REFERENCES recetas(id_receta),

    CONSTRAINT fk_ri_ingredientes
        FOREIGN KEY (id_ingrediente)
        REFERENCES ingredientes(id_ingrediente)
);

-- 7. PASOS_RECETA
CREATE TABLE pasos_receta (
    id_paso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_receta BIGINT,
    orden INT,
    descripcion TEXT,
    es_critico BOOLEAN,
    url_imagen_referencia VARCHAR(255),

    CONSTRAINT fk_pasos_receta
        FOREIGN KEY (id_receta) REFERENCES recetas(id_receta)
);

-- 8. PARTIDAS
CREATE TABLE partidas (
    id_partida BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_receta BIGINT,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20),

    CONSTRAINT fk_partidas_recetas
        FOREIGN KEY (id_receta) REFERENCES recetas(id_receta)
);

-- 9. JUGADORES_PARTIDAS
CREATE TABLE jugadores_partidas (
    id_jugador_partida BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_partida BIGINT,
    id_usuario BIGINT,

    CONSTRAINT fk_jp_partidas
        FOREIGN KEY (id_partida) REFERENCES partidas(id_partida),

    CONSTRAINT fk_jp_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

-- 10. EJECUCION_PASOS
CREATE TABLE ejecucion_pasos (
    id_ejecucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jugador_partida BIGINT,
    id_paso BIGINT,
    timestamp_inicio TIMESTAMP,
    timestamp_fin TIMESTAMP,

    CONSTRAINT fk_ep_jugadores_partidas
        FOREIGN KEY (id_jugador_partida)
        REFERENCES jugadores_partidas(id_jugador_partida),

    CONSTRAINT fk_ep_pasos_receta
        FOREIGN KEY (id_paso) REFERENCES pasos_receta(id_paso)
);

-- 11. FOTOGRAFIAS
CREATE TABLE fotografias (
    id_fotografia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejecucion BIGINT,
    url_fotografia VARCHAR(255),
    puntuacion_ia DECIMAL(5,2),

    CONSTRAINT fk_fotografias_ejecucion
        FOREIGN KEY (id_ejecucion)
        REFERENCES ejecucion_pasos(id_ejecucion)
);

-- 12. RESULTADOS
CREATE TABLE resultados (
    id_resultado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jugador_partida BIGINT,
    puntuacion_tiempo INT,
    puntuacion_proceso INT,
    puntuacion_visual INT,
    puntuacion_total INT,

    CONSTRAINT fk_resultados_jugadores_partidas
        FOREIGN KEY (id_jugador_partida)
        REFERENCES jugadores_partidas(id_jugador_partida)
);
BEGIN;

-- DROP SCHEMA speedkitchen CASCADE


CREATE SCHEMA IF NOT EXISTS speedkitchen;


-- =========================================================
-- 1. ROLES
-- =========================================================

CREATE TABLE speedkitchen.roles (
    id_rol INT GENERATED BY DEFAULT AS IDENTITY,
    nombre_rol VARCHAR(50) NOT NULL,

    CONSTRAINT pk_roles
        PRIMARY KEY (id_rol),

    CONSTRAINT uq_roles_nombre
        UNIQUE (nombre_rol),

    CONSTRAINT chk_roles_nombre_no_vacio
        CHECK (BTRIM(nombre_rol) <> '')
);


-- =========================================================
-- 2. USUARIOS
-- =========================================================

CREATE TABLE speedkitchen.usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_rol INT NOT NULL DEFAULT 1,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_usuarios
        PRIMARY KEY (id_usuario),

    CONSTRAINT uq_usuarios_email
        UNIQUE (email),

    CONSTRAINT fk_usuarios_roles
        FOREIGN KEY (id_rol)
        REFERENCES speedkitchen.roles (id_rol)
        ON DELETE RESTRICT,

    CONSTRAINT chk_usuarios_nombre_no_vacio
        CHECK (BTRIM(nombre) <> ''),

    CONSTRAINT chk_usuarios_email_formato
        CHECK (
            BTRIM(email) <> ''
            AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
        ),

    CONSTRAINT chk_usuarios_password_hash_no_vacio
        CHECK (BTRIM(password_hash) <> '')
);


-- =========================================================
-- 3. AMIGOS
-- Una sola relación por pareja, independientemente del orden.
-- =========================================================

CREATE TABLE speedkitchen.amigos (
    id_usuario_origen BIGINT NOT NULL,
    id_usuario_destino BIGINT NOT NULL,
    estado_solicitud VARCHAR(20) NOT NULL DEFAULT 'pendiente',

    CONSTRAINT pk_amigos
        PRIMARY KEY (id_usuario_origen, id_usuario_destino),

    CONSTRAINT fk_amigos_usuario_origen
        FOREIGN KEY (id_usuario_origen)
        REFERENCES speedkitchen.usuarios (id_usuario)
        ON DELETE CASCADE,

    CONSTRAINT fk_amigos_usuario_destino
        FOREIGN KEY (id_usuario_destino)
        REFERENCES speedkitchen.usuarios (id_usuario)
        ON DELETE CASCADE,

    CONSTRAINT chk_amigos_no_autosolicitud
        CHECK (id_usuario_origen <> id_usuario_destino),

    CONSTRAINT chk_amigos_estado
        CHECK (
            estado_solicitud IN ('pendiente', 'aceptada', 'rechazada')
        )
);

CREATE UNIQUE INDEX uq_amigos_pareja
    ON speedkitchen.amigos (
        LEAST(id_usuario_origen, id_usuario_destino),
        GREATEST(id_usuario_origen, id_usuario_destino)
    );


-- =========================================================
-- 4. RECETAS
-- La descripción es opcional.
-- El autor siempre debe ser un usuario existente.
-- =========================================================

CREATE TABLE speedkitchen.recetas (
    id_receta BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_autor BIGINT NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    modo_juego VARCHAR(50) NOT NULL,

    CONSTRAINT pk_recetas
        PRIMARY KEY (id_receta),

    CONSTRAINT fk_recetas_usuarios
        FOREIGN KEY (id_autor)
        REFERENCES speedkitchen.usuarios (id_usuario)
        ON DELETE RESTRICT,

    CONSTRAINT chk_recetas_nombre_no_vacio
        CHECK (BTRIM(nombre) <> ''),

    CONSTRAINT chk_recetas_modo_juego_no_vacio
        CHECK (BTRIM(modo_juego) <> ''),

    CONSTRAINT chk_recetas_descripcion_no_vacia
        CHECK (
            descripcion IS NULL
            OR BTRIM(descripcion) <> ''
        )
);


-- =========================================================
-- 5. INGREDIENTES
-- =========================================================

CREATE TABLE speedkitchen.ingredientes (
    id_ingrediente BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,

    CONSTRAINT pk_ingredientes
        PRIMARY KEY (id_ingrediente),

    CONSTRAINT uq_ingredientes_nombre
        UNIQUE (nombre),

    CONSTRAINT chk_ingredientes_nombre_no_vacio
        CHECK (BTRIM(nombre) <> '')
);


-- =========================================================
-- 6. RECETAS_INGREDIENTES
--
-- tipo_cantidad:
--   exacta   -> cantidad positiva y unidad obligatoria.
--   opcional -> cantidad positiva y unidad obligatoria;
--               la cantidad se puede omitir en la preparación.
--   al_gusto -> sin cantidad numérica.
--   pizca    -> sin cantidad numérica; unidad opcional.
-- =========================================================

CREATE TABLE speedkitchen.recetas_ingredientes (
    id_receta BIGINT NOT NULL,
    id_ingrediente BIGINT NOT NULL,
    tipo_cantidad VARCHAR(20) NOT NULL DEFAULT 'exacta',
    cantidad DECIMAL(10,2),
    unidad_medida VARCHAR(50),

    CONSTRAINT pk_recetas_ingredientes
        PRIMARY KEY (id_receta, id_ingrediente),

    CONSTRAINT fk_ri_recetas
        FOREIGN KEY (id_receta)
        REFERENCES speedkitchen.recetas (id_receta)
        ON DELETE CASCADE,

    CONSTRAINT fk_ri_ingredientes
        FOREIGN KEY (id_ingrediente)
        REFERENCES speedkitchen.ingredientes (id_ingrediente)
        ON DELETE RESTRICT,

    CONSTRAINT chk_ri_tipo_cantidad
        CHECK (
            tipo_cantidad IN ('exacta', 'opcional', 'al_gusto', 'pizca')
        ),

    CONSTRAINT chk_ri_cantidad_segun_tipo
        CHECK (
            (
                tipo_cantidad IN ('exacta', 'opcional')
                AND cantidad IS NOT NULL
                AND cantidad > 0
                AND unidad_medida IS NOT NULL
                AND BTRIM(unidad_medida) <> ''
            )
            OR
            (
                tipo_cantidad = 'al_gusto'
                AND cantidad IS NULL
                AND (
                    unidad_medida IS NULL
                    OR BTRIM(unidad_medida) <> ''
                )
            )
            OR
            (
                tipo_cantidad = 'pizca'
                AND cantidad IS NULL
                AND (
                    unidad_medida IS NULL
                    OR BTRIM(unidad_medida) <> ''
                )
            )
        )
);


-- =========================================================
-- 7. PASOS_RECETA
-- descripcion y url_imagen_referencia son opcionales.
-- Cada receta debe tener un orden de pasos sin duplicados.
-- =========================================================

CREATE TABLE speedkitchen.pasos_receta (
    id_paso BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_receta BIGINT NOT NULL,
    orden INT NOT NULL,
    descripcion TEXT,
    es_critico BOOLEAN NOT NULL,
    url_imagen_referencia VARCHAR(255),

    CONSTRAINT pk_pasos_receta
        PRIMARY KEY (id_paso),

    CONSTRAINT fk_pasos_receta
        FOREIGN KEY (id_receta)
        REFERENCES speedkitchen.recetas (id_receta)
        ON DELETE CASCADE,

    CONSTRAINT uq_pasos_receta_orden
        UNIQUE (id_receta, orden),

    CONSTRAINT chk_pasos_orden_positivo
        CHECK (orden > 0),

    CONSTRAINT chk_pasos_descripcion_no_vacia
        CHECK (
            descripcion IS NULL
            OR BTRIM(descripcion) <> ''
        ),

    CONSTRAINT chk_pasos_url_no_vacia
        CHECK (
            url_imagen_referencia IS NULL
            OR BTRIM(url_imagen_referencia) <> ''
        )
);


-- =========================================================
-- 8. PARTIDAS
-- =========================================================

CREATE TABLE speedkitchen.partidas (
    id_partida BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_receta BIGINT NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',

    CONSTRAINT pk_partidas
        PRIMARY KEY (id_partida),

    CONSTRAINT fk_partidas_recetas
        FOREIGN KEY (id_receta)
        REFERENCES speedkitchen.recetas (id_receta)
        ON DELETE RESTRICT,

    CONSTRAINT chk_partidas_estado
        CHECK (
            estado IN ('pendiente', 'en_curso', 'finalizada', 'cancelada')
        )
);


-- =========================================================
-- 9. JUGADORES_PARTIDAS
-- Un usuario solo puede participar una vez en cada partida.
-- =========================================================

CREATE TABLE speedkitchen.jugadores_partidas (
    id_jugador_partida BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_partida BIGINT NOT NULL,
    id_usuario BIGINT NOT NULL,

    CONSTRAINT pk_jugadores_partidas
        PRIMARY KEY (id_jugador_partida),

    CONSTRAINT fk_jp_partidas
        FOREIGN KEY (id_partida)
        REFERENCES speedkitchen.partidas (id_partida)
        ON DELETE CASCADE,

    CONSTRAINT fk_jp_usuarios
        FOREIGN KEY (id_usuario)
        REFERENCES speedkitchen.usuarios (id_usuario)
        ON DELETE RESTRICT,

    CONSTRAINT uq_jp_partida_usuario
        UNIQUE (id_partida, id_usuario)
);


-- =========================================================
-- 10. EJECUCION_PASOS
-- timestamp_fin es NULL mientras el paso siga en ejecución.
-- =========================================================

CREATE TABLE speedkitchen.ejecucion_pasos (
    id_ejecucion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_jugador_partida BIGINT NOT NULL,
    id_paso BIGINT NOT NULL,
    timestamp_inicio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    timestamp_fin TIMESTAMP,

    CONSTRAINT pk_ejecucion_pasos
        PRIMARY KEY (id_ejecucion),

    CONSTRAINT fk_ep_jugadores_partidas
        FOREIGN KEY (id_jugador_partida)
        REFERENCES speedkitchen.jugadores_partidas (id_jugador_partida)
        ON DELETE CASCADE,

    CONSTRAINT fk_ep_pasos_receta
        FOREIGN KEY (id_paso)
        REFERENCES speedkitchen.pasos_receta (id_paso)
        ON DELETE RESTRICT,

    CONSTRAINT chk_ep_tiempos_coherentes
        CHECK (
            timestamp_fin IS NULL
            OR timestamp_fin >= timestamp_inicio
        )
);


-- =========================================================
-- 11. FOTOGRAFIAS
-- Toda fotografía debe pertenecer a una ejecución.
-- Al eliminar la ejecución, se eliminan sus fotografías.
-- puntuacion_ia es opcional hasta que se analice la foto.
-- =========================================================

CREATE TABLE speedkitchen.fotografias (
    id_fotografia BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_ejecucion BIGINT NOT NULL,
    url_fotografia VARCHAR(255) NOT NULL,
    puntuacion_ia DECIMAL(5,2),

    CONSTRAINT pk_fotografias
        PRIMARY KEY (id_fotografia),

    CONSTRAINT fk_fotografias_ejecucion
        FOREIGN KEY (id_ejecucion)
        REFERENCES speedkitchen.ejecucion_pasos (id_ejecucion)
        ON DELETE CASCADE,

    CONSTRAINT chk_fotografias_url_no_vacia
        CHECK (BTRIM(url_fotografia) <> ''),

    CONSTRAINT chk_fotografias_puntuacion_ia
        CHECK (
            puntuacion_ia IS NULL
            OR puntuacion_ia BETWEEN 0 AND 100
        )
);


-- =========================================================
-- 12. RESULTADOS
-- Las puntuaciones pueden ser NULL hasta que la aplicación
-- las calcule.
-- =========================================================

CREATE TABLE speedkitchen.resultados (
    id_resultado BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_jugador_partida BIGINT NOT NULL,
    puntuacion_tiempo INT,
    puntuacion_proceso INT,
    puntuacion_visual INT,
    puntuacion_total INT,

    CONSTRAINT pk_resultados
        PRIMARY KEY (id_resultado),

    CONSTRAINT fk_resultados_jugadores_partidas
        FOREIGN KEY (id_jugador_partida)
        REFERENCES speedkitchen.jugadores_partidas (id_jugador_partida)
        ON DELETE CASCADE,

    CONSTRAINT chk_resultados_puntuacion_tiempo
        CHECK (
            puntuacion_tiempo IS NULL
            OR puntuacion_tiempo BETWEEN 0 AND 100
        ),

    CONSTRAINT chk_resultados_puntuacion_proceso
        CHECK (
            puntuacion_proceso IS NULL
            OR puntuacion_proceso BETWEEN 0 AND 100
        ),

    CONSTRAINT chk_resultados_puntuacion_visual
        CHECK (
            puntuacion_visual IS NULL
            OR puntuacion_visual BETWEEN 0 AND 100
        ),

    CONSTRAINT chk_resultados_puntuacion_total
        CHECK (
            puntuacion_total IS NULL
            OR puntuacion_total BETWEEN 0 AND 100
        )
);


COMMIT;
